import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

const require = createRequire(import.meta.url);
const { _electron } = require(process.argv[2] || 'playwright');
const executablePath = path.resolve(process.argv[3] || 'release/win-unpacked/DataAgent.exe');
const directory = path.resolve('artifacts', `desktop-check-${Date.now()}`);
await mkdir(directory, { recursive: true });
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const app = await _electron.launch({ executablePath, args: [`--dataagent-user-data=${directory}`], env, timeout: 30000 });
const errors = [];
try {
  const page = await app.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('heading', { name: /让数据，指引下一步/ }).waitFor();
  const runtime = await app.evaluate(({ app }) => ({ packaged: app.isPackaged, version: app.getVersion() }));
  assert.equal(runtime.packaged, true);
  const bootstrap = await page.evaluate(async () => (await fetch('/api/bootstrap')).json());
  assert.equal(bootstrap.wallet.balance, 500);
  await page.getByRole('button', { name: '新建分析', exact: true }).first().click();
  await page.getByRole('dialog').getByLabel('分析名称', { exact: true }).fill('桌面程序实际验收');
  await page.getByRole('dialog').getByRole('button', { name: /协作模式/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: '开始分析', exact: true }).click();
  await page.getByRole('button', { name: '确认并继续', exact: true }).waitFor();
  await page.getByLabel('发送给分析搭档的消息').fill('重点检查自然渠道新增和留存。');
  await page.getByRole('button', { name: '确认并继续', exact: true }).click();
  await page.getByText('分析结果已整理，确认后生成报告。', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(directory, 'collaboration.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '确认并继续', exact: true }).click();
  await page.locator('.run-status-card strong').filter({ hasText: '分析完成，报告已就绪' }).waitFor();
  await page.getByRole('tab', { name: '完整报告', exact: true }).click();
  await page.getByText('运营摘要', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(directory, 'report.png'), animations: 'disabled' });
  const completed = await page.evaluate(async () => (await fetch('/api/bootstrap')).json());
  const task = completed.tasks.find(t => t.title === '桌面程序实际验收');
  assert.equal(task.status, 'completed');
  assert.equal(task.steps.filter(s => s.status === 'completed').length, 8);
  assert.ok(task.report.metrics.length >= 8);
  assert.equal(completed.wallet.balance, 480);
  assert.equal(completed.wallet.frozen, 0);
  const markdown = await page.evaluate(async id => (await fetch(`/api/tasks/${id}/report.md`)).text(), task.id);
  assert.match(markdown, /自然渠道/);
  await page.getByRole('button', { name: '新建分析', exact: true }).first().click();
  await page.getByRole('dialog').getByLabel('分析名称', { exact: true }).fill('桌面自动模式验收');
  await page.getByRole('dialog').getByRole('button', { name: /自动模式/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: '开始分析', exact: true }).click();
  await page.locator('.run-status-card strong').filter({ hasText: '分析完成，报告已就绪' }).waitFor();
  assert.equal(await page.getByRole('button', { name: '确认并继续', exact: true }).count(), 0);
  const final = await page.evaluate(async () => (await fetch('/api/bootstrap')).json());
  assert.equal(final.wallet.balance, 460);
  await page.reload();
  await page.getByRole('heading', { name: /让数据，指引下一步/ }).waitFor();
  const persisted = await page.evaluate(async () => (await fetch('/api/bootstrap')).json());
  assert.equal(persisted.tasks.filter(t => t.title.startsWith('桌面')).length, 2);
  assert.equal(persisted.wallet.spent, 40);
  assert.deepEqual(errors, []);
  const result = { passed: true, ...runtime, collaborative: true, automatic: true, report: true, wallet: persisted.wallet, errors };
  await writeFile(path.join(directory, 'result.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify({ ...result, directory }, null, 2));
} finally { await app.close(); }
